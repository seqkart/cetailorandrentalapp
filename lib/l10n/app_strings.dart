String localizedUiText(BuildContext context, String source) {
  final language = Localizations.localeOf(context).languageCode;
  if (source.startsWith('Measurements (')) {
    return switch (language) {
      'hi' => source.replaceFirst('Measurements', 'माप'),
      'pa' => source.replaceFirst('Measurements', 'ਮਾਪ'),
      _ => source,
    };
  }
  if (source.startsWith('Choose criteria to refine ')) {
    return switch (language) {
      'hi' => 'रिपोर्ट के लिए फ़िल्टर चुनें।',
      'pa' => 'ਰਿਪੋਰਟ ਲਈ ਫ਼ਿਲਟਰ ਚੁਣੋ।',
      _ => source,
    };
  }
  if (source.startsWith('Signed in as ')) {
    final name = source
        .substring('Signed in as '.length)
        .replaceFirst('. Enter your MPIN.', '');
    return switch (language) {
      'hi' => '$name के रूप में साइन इन हैं। अपना MPIN दर्ज करें।',
      'pa' => '$name ਵਜੋਂ ਸਾਈਨ ਇਨ ਹੋ। ਆਪਣਾ MPIN ਭਰੋ।',
      _ => source,
    };
  }
  final countMatch = RegExp(r'^(\d+) (records?|rows)$').firstMatch(source);
  if (countMatch != null && (language == 'hi' || language == 'pa')) {
    final count = countMatch.group(1)!;
    final item = switch (countMatch.group(2)) {
      'record' || 'records' => switch (language) {
        'hi' => 'रिकॉर्ड',
        'pa' => 'ਰਿਕਾਰਡ',
        _ => 'records',
      },
      _ => switch (language) {
        'hi' => 'पंक्तियाँ',
        'pa' => 'ਕਤਾਰਾਂ',
        _ => 'rows',
      },
    };
    return '$count $item';
  }
  final activeCount = RegExp(r'^(\d+) active$').firstMatch(source);
  if (activeCount != null) {
    return switch (language) {
      'hi' => '${activeCount.group(1)} सक्रिय',
      'pa' => '${activeCount.group(1)} ਚਾਲੂ',
      _ => source,
    };
  }
  final actionCount = RegExp(r'^(Assign|Received|Files) \((\d+)\)$')
      .firstMatch(source);
  if (actionCount != null) {
    final action = localizedUiText(context, actionCount.group(1)!);
    return '$action (${actionCount.group(2)})';
  }
  final orderDetails = RegExp(r'^(Order|Invoice|Rental) (.*) details$')
      .firstMatch(source);
  if (orderDetails != null && (language == 'hi' || language == 'pa')) {
    final noun = localizedUiText(context, '${orderDetails.group(1)} details');
    return '$noun · ${orderDetails.group(2)}';
  }
  if (source.startsWith('Measurements · ')) {
    return '${localizedUiText(context, 'Measurements')} · '
        '${source.substring('Measurements · '.length)}';
  }
  final translation = switch (language) {
    'hi' => _hindiUiCopy[source],
    'pa' => _punjabiUiCopy[source],
    _ => null,
  };
  return translation ?? source;
}

